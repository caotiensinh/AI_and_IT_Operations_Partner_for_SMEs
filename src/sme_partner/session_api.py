"""Protected read-only API slice using an opaque first-party bearer session.

No OIDC login callback exists yet. Production issuance requires a separate
trusted Authorization Code + PKCE + nonce flow with server-side session minting.
"""
from __future__ import annotations

import hashlib
import re
from collections.abc import Callable
from uuid import UUID

import psycopg
from fastapi import FastAPI, Header, HTTPException, Response

from .rbac import Action, Assignment, PermissionDenied, Resource, Role, ScopeType, require_permission
from .tenant_context import AuthorizedTenantContext, TenantAccessDenied

# 32 random bytes base64url without padding, generated by server-side secrets.
TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{43}$")


def _digest(authorization: str | None) -> bytes:
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(401, "authentication required", headers={"WWW-Authenticate": "Bearer"})
    token = authorization[7:]
    if not TOKEN_RE.fullmatch(token):
        raise HTTPException(401, "invalid session", headers={"WWW-Authenticate": "Bearer"})
    return hashlib.sha256(token.encode("ascii")).digest()


def create_app(connect: Callable[[], psycopg.Connection]) -> FastAPI:
    app = FastAPI(title="SME Partner Protected API", version="0.1.0")

    @app.get("/v1/tenants/{tenant_id}/assets")
    def list_assets(tenant_id: UUID, authorization: str | None = Header(default=None)):
        digest = _digest(authorization)
        with connect() as conn:
            with conn.transaction():
                # Runtime API privilege: never use the provisioning or table-owner role.
                conn.execute("SET LOCAL ROLE sme_app")
                row = conn.execute("SELECT sme.resolve_session(%s,%s)", (digest, tenant_id)).fetchone()
                if not row or row[0] is None:
                    raise HTTPException(403, "tenant access denied")
                identity_id = row[0]
                conn.execute("SELECT set_config('sme.tenant_id',%s,true)", (str(tenant_id),))
                grants = conn.execute(
                    "SELECT role,scope_type,site_id,department_id FROM sme.role_assignments "
                    "WHERE tenant_id=%s AND identity_id=%s",
                    (tenant_id, identity_id),
                ).fetchall()
                assignments = tuple(
                    Assignment(
                        tenant_id=tenant_id, identity_id=identity_id,
                        role=Role(role), scope_type=ScopeType(scope_type),
                        scope_id=site_id if scope_type == "site" else
                            dept_id if scope_type == "department" else None,
                    )
                    for role,scope_type,site_id,dept_id in grants
                )
                data = conn.execute(
                    "SELECT id,site_id,name FROM sme.assets WHERE tenant_id=%s ORDER BY name,id",
                    (tenant_id,),
                ).fetchall()
                context = AuthorizedTenantContext(identity_id, tenant_id)
                items = []
                for asset_id, site_id, name in data:
                    try:
                        require_permission(context, assignments, Action.READ,
                                           Resource(tenant_id, site_id))
                    except (PermissionDenied, TenantAccessDenied):
                        continue
                    items.append({"id": str(asset_id), "site_id": str(site_id), "name": name})
                return {"tenant_id": str(tenant_id), "assets": items}

    @app.post("/v1/session/logout", status_code=204)
    def logout(authorization: str | None = Header(default=None)):
        digest = _digest(authorization)
        with connect() as conn:
            with conn.transaction():
                conn.execute("SET LOCAL ROLE sme_app")
                conn.execute("SELECT sme.revoke_session(%s)", (digest,))
        return Response(status_code=204)

    return app
